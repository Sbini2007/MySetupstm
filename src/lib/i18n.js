export function getStoredLanguage() {
  if (typeof window === "undefined") return "it";
  return window.localStorage.getItem(STORAGE_KEY) || "it";
}

export function setStoredLanguage(code) {
  if (typeof window === "undefined") return;
  window.localStorage.setItem(STORAGE_KEY, code);
  window.dispatchEvent(new CustomEvent("mysetups:language", { detail: code }));
}

export function useLanguage() {
  const [language, setLanguage] = useState("it");

  useEffect(() => {
    const sync = (event) => {
      const next = event?.detail || getStoredLanguage();
      setLanguage(next);
      document.documentElement.lang = next;
    };
    sync();
    window.addEventListener("mysetups:language", sync);
    window.addEventListener("storage", sync);
    return () => {
      window.removeEventListener("mysetups:language", sync);
      window.removeEventListener("storage", sync);
    };
  }, []);

  const t = (key) => dictionary[language]?.[key] || dictionary.it[key] || key;
  return { language, setLanguage: setStoredLanguage, t };
}
